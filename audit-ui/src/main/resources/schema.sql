-- Review decisions made in the audit UI. Portable SQL (PostgreSQL and H2).
-- audit_review    : the current decision per event.
-- audit_review_log: append-only history, so a review is itself auditable (who, when, what, note).
CREATE TABLE IF NOT EXISTS audit_review (
  event_id    VARCHAR(64)   PRIMARY KEY,
  status      VARCHAR(16)   NOT NULL,
  reviewer    VARCHAR(255)  NOT NULL,
  reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL,
  note        VARCHAR(2000)
);
CREATE TABLE IF NOT EXISTS audit_review_log (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id    VARCHAR(64)   NOT NULL,
  status      VARCHAR(16)   NOT NULL,
  reviewer    VARCHAR(255)  NOT NULL,
  reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL,
  note        VARCHAR(2000)
);
CREATE INDEX IF NOT EXISTS idx_audit_review_status ON audit_review (status, reviewed_at);
CREATE INDEX IF NOT EXISTS idx_audit_review_log_event ON audit_review_log (event_id);

-- Per-person display preferences (language, time zone, how times are shown, theme, density).
CREATE TABLE IF NOT EXISTS user_pref (
  username     VARCHAR(255) PRIMARY KEY,
  language     VARCHAR(8)   NOT NULL,
  time_zone    VARCHAR(64)  NOT NULL,
  time_display VARCHAR(8)   NOT NULL,
  clock24      BOOLEAN      NOT NULL,
  show_utc     BOOLEAN      NOT NULL,
  theme        VARCHAR(8)   NOT NULL,
  density      VARCHAR(12)  NOT NULL,
  updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Systems that have sent audit records (a Keycloak client id each). Found automatically from recent records;
-- an administrator can give each a readable name.
CREATE TABLE IF NOT EXISTS sending_system (
  client_id    VARCHAR(255) PRIMARY KEY,
  display_name VARCHAR(120),
  note         VARCHAR(255),
  first_seen   TIMESTAMP WITH TIME ZONE NOT NULL,
  last_seen    TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_by   VARCHAR(255)
);

-- Small key/value settings an administrator may change (for example the registry address).
CREATE TABLE IF NOT EXISTS app_setting (
  setting_key   VARCHAR(80) PRIMARY KEY,
  setting_value VARCHAR(500),
  updated_by    VARCHAR(255),
  updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Every consent check made before patient details are shown (who asked, about whom, what the consent service answered).
CREATE TABLE IF NOT EXISTS consent_check_log (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checked_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  username    VARCHAR(255) NOT NULL,
  patient_ref VARCHAR(255) NOT NULL,
  actor_role  VARCHAR(64),
  purpose     VARCHAR(64),
  decision    VARCHAR(16) NOT NULL,
  reason      VARCHAR(255),
  consent_id  VARCHAR(128)
);

-- ── Reviews (cases), added by the Reviews screen ─────────────────────────────────────────────────────────────
-- review_case: one case that needs a person to decide. status: new | review | second | escalated | done.
-- A case closes when two reviewers agree (or the privacy officer rules). A closed case is locked: fingerprint is a SHA-256 over its content.
CREATE TABLE IF NOT EXISTS review_case (
  id              VARCHAR(16)   PRIMARY KEY,
  seq             BIGINT        NOT NULL,
  kind            VARCHAR(24)   NOT NULL,
  title           VARCHAR(200)  NOT NULL,
  subject         VARCHAR(200),
  patient_ref     VARCHAR(64),
  facility        VARCHAR(120),
  explore_qs      VARCHAR(300),
  status          VARCHAR(12)   NOT NULL,
  opened_at       TIMESTAMP WITH TIME ZONE NOT NULL,
  opened_by       VARCHAR(255)  NOT NULL,
  due_at          TIMESTAMP WITH TIME ZONE NOT NULL,
  assignee        VARCHAR(255),
  second_reviewer VARCHAR(255),
  draft_decision  VARCHAR(16),
  draft_note      VARCHAR(2000),
  outcome         VARCHAR(16),
  closed_at       TIMESTAMP WITH TIME ZONE,
  fingerprint     VARCHAR(64),
  reopen_of       VARCHAR(16),
  demo_seed       BOOLEAN       NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_review_case_status ON review_case (status, opened_at);
CREATE TABLE IF NOT EXISTS review_case_event (
  case_id  VARCHAR(16) NOT NULL,
  event_id VARCHAR(64) NOT NULL,
  PRIMARY KEY (case_id, event_id)
);
CREATE INDEX IF NOT EXISTS idx_review_case_event_ev ON review_case_event (event_id);
-- one row per decision (first reviewer, second reviewer, privacy officer)
CREATE TABLE IF NOT EXISTS review_case_decision (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id    VARCHAR(16)   NOT NULL,
  role       VARCHAR(12)   NOT NULL,
  reviewer   VARCHAR(255)  NOT NULL,
  decision   VARCHAR(16)   NOT NULL,
  note       VARCHAR(2000),
  decided_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_review_case_decision_case ON review_case_decision (case_id);
-- what happened so far (append-only)
CREATE TABLE IF NOT EXISTS review_case_log (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id  VARCHAR(16)   NOT NULL,
  at       TIMESTAMP WITH TIME ZONE NOT NULL,
  actor    VARCHAR(255)  NOT NULL,
  code     VARCHAR(24)   NOT NULL,
  arg      VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS idx_review_case_log_case ON review_case_log (case_id);

-- ── Alerts, added by the Alerts screen ───────────────────────────────────────────────────────────────────────
-- alert_firing: one row each time a rule fired. In this build only the demo seed writes it (no rule engine yet: Planned).
CREATE TABLE IF NOT EXISTS alert_firing (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_id       VARCHAR(40)   NOT NULL,
  fired_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  severity      VARCHAR(8)    NOT NULL,
  subject       VARCHAR(200),
  facility      VARCHAR(120),
  amount        INT,
  case_id       VARCHAR(16),
  marked_normal BOOLEAN       NOT NULL DEFAULT FALSE,
  marked_by     VARCHAR(255),
  demo_seed     BOOLEAN       NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_alert_firing_rule ON alert_firing (rule_id, fired_at);
